/**
 * Returns complete quote with converted IDR and USD values.
 */
export function getLiveQuote(assetCode: string, fxRate = DEFAULT_USD_IDR_RATE): MarketAssetQuote {
  const item = MARKET_CATALOG[assetCode];
  if (!item) {
    // Generate fallback quote for custom custom asset
    const isCrypto = assetCode.startsWith('CRYPTO_') || ['BTC', 'ETH', 'SOL'].includes(assetCode);
    return {
      assetCode,
      name: assetCode,
      ticker: assetCode,
      category: isCrypto ? 'CRYPTO' : 'INDONESIAN_EQUITY',
      categoryLabel: isCrypto ? 'Crypto Asset' : 'Custom Asset',
      priceIdr: 100000.0,
      priceUsd: 100000.0 / fxRate,
      change24hPercent: 0.0,
      annualYield: 0.0,
      expectedCagr: 0.10,
      annualVolatility: 0.25,
      decimals: isCrypto ? 8 : 2,
      color: '#64748B',
      badgeClass: 'bg-slate-500/10 text-slate-300 border-slate-500/20',
    };
  }

  let priceIdr: number;
  let priceUsd: number;

  if (item.basePriceIdr !== undefined) {
    priceIdr = item.basePriceIdr;
    priceUsd = item.basePriceIdr / fxRate;
  } else if (item.basePriceUsd !== undefined) {
    priceUsd = item.basePriceUsd;
    priceIdr = item.basePriceUsd * fxRate;
  } else {
    priceIdr = 1.0;
    priceUsd = 1.0 / fxRate;
  }

  return {
    assetCode: item.assetCode,
    name: item.name,
    ticker: item.ticker,
    category: item.category,
    categoryLabel: item.categoryLabel,
    priceIdr: Math.round(priceIdr * 100) / 100,
    priceUsd: Math.round(priceUsd * 100) / 100,
    change24hPercent: item.change24hPercent,
    annualYield: item.annualYield,
    expectedCagr: item.expectedCagr,
    annualVolatility: item.annualVolatility,
    decimals: item.decimals,
    color: item.color,
    badgeClass: item.badgeClass,
  };
}

export function getAllLiveQuotes(fxRate = DEFAULT_USD_IDR_RATE): MarketAssetQuote[] {
  return Object.keys(MARKET_CATALOG).map((code) => getLiveQuote(code, fxRate));
}

export function searchAssetCatalog(
  query: string,
  fxRate = DEFAULT_USD_IDR_RATE,
  category?: string
): MarketAssetQuote[] {
  const q = query.trim().toLowerCase();
  let quotes = getAllLiveQuotes(fxRate);

  if (category && category !== 'ALL') {
    quotes = quotes.filter((quote) => quote.category === category);
  }

  if (!q) return quotes;

  return quotes.filter(
    (quote) =>
      quote.assetCode.toLowerCase().includes(q) ||
      quote.name.toLowerCase().includes(q) ||
      quote.ticker.toLowerCase().includes(q) ||
      quote.categoryLabel.toLowerCase().includes(q)
  );
}
